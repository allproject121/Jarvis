package com.jarvis.assistant.androllm.chat.model

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * A chat conversation (ported from AndroLLM core/models Conversation).
 * Lives in the separate `androllm_chat.db` — never in a Jarvis database.
 */
@Serializable
data class Conversation(
    val id: String,
    val title: String,
    val createdAt: Long,
    val updatedAt: Long,
    val lastMessagePreview: String? = null,
    val messageCount: Int = 0,
    val isPinned: Boolean = false,
    val isArchived: Boolean = false
)

/** Role of a chat message (ported from AndroLLM core/models MessageRole). */
@Serializable
enum class MessageRole {
    @SerialName("user")
    USER,

    @SerialName("assistant")
    ASSISTANT,

    @SerialName("system")
    SYSTEM
}

/** Where a message came from (ported from AndroLLM core/models MessageOrigin). */
@Serializable
enum class MessageOrigin {
    /** Sent from the keyboard / chat input. */
    TYPED,

    /** Captured by a voice assistant. */
    VOICE,

    /** Generated by an automation / importer (e.g. the Jarvis history import). */
    AUTOMATION;

    val isVoice: Boolean get() = this == VOICE
}

/**
 * A single message inside a conversation (ported from AndroLLM core/models Message).
 *
 * [attachmentsJson] holds the files attached to this message as a JSON array of
 * [com.jarvis.assistant.androllm.attachments.model.ChatAttachment] ("" = none).
 */
@Serializable
data class Message(
    val id: String,
    val conversationId: String,
    val role: MessageRole,
    val content: String,
    val timestamp: Long,
    val isPending: Boolean = false,
    val modelId: String? = null,
    val isBookmarked: Boolean = false,
    val origin: MessageOrigin = MessageOrigin.TYPED,
    val attachmentsJson: String = ""
)
